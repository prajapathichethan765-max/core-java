class TvShows{
	static String shows(String showOne , String showTwo , String showThree , String showFour){
		System.out.println(showOne);
		System.out.println(showTwo);
		System.out.println(showThree);
		System.out.println(showFour);
		
		String showsNamws[] = {showOne , showTwo , showThree , showFour};
		
		System.out.println(showsNamws[0]);
		System.out.println(showsNamws[1]);
		System.out.println(showsNamws[2]);
		System.out.println(showsNamws[3]);
		
		return showOne +" " + showTwo + " " + showThree +" " + showFour ;
	}
}
