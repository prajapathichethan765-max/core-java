class EmployeeSalaries{
	public static void main(String[] args){
		long salary1 = 250000L;
		long salary2 = 350000L;
		long salary3 = 450000L;
		long salary4 = 550000L;

		System.out.println(salary1);
		System.out.println(salary2);
		System.out.println(salary3);
		System.out.println(salary4);

		long salaries[] = {salary1, salary2, salary3, salary4};

		System.out.println(salaries[0]);
		System.out.println(salaries[1]);
		System.out.println(salaries[2]);
		System.out.println(salaries[3]);
	}
}