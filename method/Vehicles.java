class Vehicles{
	public static void main(String[] args){
		String vehicle1 = "car";
		String vehicle2 = "bike";
		String vehicle3 = "truck";
		String vehicle4 = "bus";

		System.out.println(vehicle1);
		System.out.println(vehicle2);
		System.out.println(vehicle3);
		System.out.println(vehicle4);

		String vehicles[] = {vehicle1, vehicle2, vehicle3, vehicle4};

		System.out.println(vehicles[0]);
		System.out.println(vehicles[1]);
		System.out.println(vehicles[2]);
		System.out.println(vehicles[3]);
	}
}