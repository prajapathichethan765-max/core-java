class ProgrammingLanguages{
	public static void main(String[] args){
		String language1 = "java";
		String language2 = "python";
		String language3 = "c++";
		String language4 = "javascript";

		System.out.println(language1);
		System.out.println(language2);
		System.out.println(language3);
		System.out.println(language4);

		String languages[] = {language1, language2, language3, language4};

		System.out.println(languages[0]);
		System.out.println(languages[1]);
		System.out.println(languages[2]);
		System.out.println(languages[3]);
	}
}