class Birds{
	public static void main(String[] args){
		String bird1 = "parrot";
		String bird2 = "eagle";
		String bird3 = "pigeon";
		String bird4 = "peacock";

		System.out.println(bird1);
		System.out.println(bird2);
		System.out.println(bird3);
		System.out.println(bird4);

		String birds[] = {bird1, bird2, bird3, bird4};

		System.out.println(birds[0]);
		System.out.println(birds[1]);
		System.out.println(birds[2]);
		System.out.println(birds[3]);
	}
}