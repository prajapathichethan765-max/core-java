class MusicalInstruments{
	public static void main(String[] args){
		String instrument1 = "guitar";
		String instrument2 = "piano";
		String instrument3 = "violin";
		String instrument4 = "flute";

		System.out.println(instrument1);
		System.out.println(instrument2);
		System.out.println(instrument3);
		System.out.println(instrument4);

		String instruments[] = {instrument1, instrument2, instrument3, instrument4};

		System.out.println(instruments[0]);
		System.out.println(instruments[1]);
		System.out.println(instruments[2]);
		System.out.println(instruments[3]);
	}
}