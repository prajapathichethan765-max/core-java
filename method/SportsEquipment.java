class SportsEquipment{
	public static void main(String[] args){
		String item1 = "cricket bat";
		String item2 = "football";
		String item3 = "hockey stick";
		String item4 = "tennis racket";

		System.out.println(item1);
		System.out.println(item2);
		System.out.println(item3);
		System.out.println(item4);

		String equipment[] = {item1, item2, item3, item4};

		System.out.println(equipment[0]);
		System.out.println(equipment[1]);
		System.out.println(equipment[2]);
		System.out.println(equipment[3]);
	}
}