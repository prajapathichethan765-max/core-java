class Flowers{
	public static void main(String[] args){
		String flower1 = "rose";
		String flower2 = "lotus";
		String flower3 = "jasmine";
		String flower4 = "sunflower";

		System.out.println(flower1);
		System.out.println(flower2);
		System.out.println(flower3);
		System.out.println(flower4);

		String flowers[] = {flower1, flower2, flower3, flower4};

		System.out.println(flowers[0]);
		System.out.println(flowers[1]);
		System.out.println(flowers[2]);
		System.out.println(flowers[3]);
	}
}